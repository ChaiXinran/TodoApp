  await context.setOffline(true);
  const cacheDiagnostic=await page.evaluate(async()=>({controller:navigator.serviceWorker.controller?.scriptURL,caches:await caches.keys(),cachedRoot:!!(await caches.match(new URL('index.html',location.href).href)),fetchStatus:await fetch('index.html').then(r=>r.status).catch(e=>String(e))}));
  console.log('OFFLINE_CACHE',JSON.stringify(cacheDiagnostic));
  let offlineNavigation=true;
  try{await page.reload({waitUntil:'domcontentloaded'});}catch(e){
    if(!useWebkit)throw e;
    offlineNavigation=false;
    fs.writeFileSync('.verification/webkit-offline-limitation.json',JSON.stringify({error:String(e),cacheDiagnostic},null,2));
    await context.setOffline(false);await page.reload({waitUntil:'domcontentloaded'});
  }
  await page.waitForFunction(()=>!document.getElementById('loading'),{},{timeout:60000});

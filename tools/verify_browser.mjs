  await page.waitForFunction(()=>document.documentElement.hasAttribute('data-richang-test'),{},{timeout:120000});
  const result=JSON.parse(await page.locator('html').getAttribute('data-richang-test'));console.log('DATA',JSON.stringify(result));
  if(result.status==='failed')throw Error(result.error);
  await page.reload();
  await page.waitForFunction(()=>document.documentElement.hasAttribute('data-richang-test'),{},{timeout:60000});
  const reopened=JSON.parse(await page.locator('html').getAttribute('data-richang-test'));
  console.log('REOPENED',JSON.stringify(reopened));
  if(reopened.status!=='reopened'||!reopened.photo)throw Error('Reload persistence failed');
  await page.goto('http://127.0.0.1:8765/__production');
  await page.waitForFunction(()=>!document.getElementById('loading'),{},{timeout:60000});
  await page.screenshot({path:`screenshots/${useWebkit?'webkit':'chrome'}-home.png`});
  const enable=page.locator('flt-semantics-placeholder');
  if(await enable.count())await enable.evaluate(n=>n.click());
  await page.waitForTimeout(1000);
  const prefix=useWebkit?'webkit':'chrome';
  await page.getByRole('button',{name:'选图',exact:true}).click();
  await page.getByRole('button',{name:'添加云次方图文',exact:true}).click();
  await page.getByRole('textbox',{name:'标题（可选）',exact:true}).click();
  await page.keyboard.insertText('PWA-Photo-UI');
  await page.keyboard.press('Tab');
  const imageChooserPromise=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'从相册添加图片',exact:true}).click();
  const imageChooser=await imageChooserPromise;await imageChooser.setFiles('assets/branding/richang_cover.png');
  await page.getByRole('button',{name:'更换图片',exact:true}).waitFor();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:'添加云次方图文',exact:true}).waitFor();
  await page.getByRole('button',{name:'返回',exact:true}).click();
  for(const [name,file] of [['日历','calendar'],['事务','affairs'],['记录','records'],['档案','archive']]) {
    await page.getByRole('tab',{name,exact:true}).click();
    await page.waitForTimeout(200);
    await page.screenshot({path:`screenshots/${prefix}-${file}.png`});
  }
  await page.getByRole('button',{name:'使用与备份',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出全部数据与图片',exact:true}).click();
  const download=await downloadPromise;await download.saveAs('.verification/browser-backup.json');
  const backup=JSON.parse(fs.readFileSync('.verification/browser-backup.json','utf8'));
  if(!backup.tables.cloud_posts.some(r=>r.title==='PWA-Photo-UI'&&(r.image_path||'').startsWith('data:')))throw Error('Picked image not durably saved');
  if(backup.app!=='richang-pwa'||backup.tables.courses.length!==11||!backup.tables.entries.some(r=>(r.image_path||'').startsWith('data:')))throw Error('Exported backup incomplete');
  const chooserPromise=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'从备份恢复',exact:true}).click();
  const chooser=await chooserPromise;await chooser.setFiles('.verification/browser-backup.json');
  await page.getByRole('button',{name:'替换并恢复',exact:true}).click();
  await page.waitForTimeout(500);
  console.log('RESTORE_ARIA',await page.locator('body').ariaSnapshot());
  await page.getByText('恢复完成。返回后会重新读取数据。',{exact:false}).waitFor();
